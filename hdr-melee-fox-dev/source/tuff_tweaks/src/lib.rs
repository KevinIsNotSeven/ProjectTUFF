// Real copies of the vanilla scripts (generated by gen_vanilla_acmd.py from the dumped game
// scripts). Calling the game's original script functions from inside smashline crashed, so the
// scripts themselves are compiled in here instead.
mod vanilla_acmd;

// K. Rool status scripts HDR overrides -> vanilla.
//
// smashline has no priority for status scripts: the last plugin to register one wins, and HDR's
// plugin.nro is loaded by ARCropolis after the skyline plugins, so registering ours the normal
// way lost to HDR (up B played HDR's motions -> T-pose; neutral B had HDR's grab instead of the
// suction). Instead, once the status table is built, the game's own functions are written back
// into it directly, and that is re-checked every frame in case anything puts HDR's back.
mod krool_status {
    use super::*;
    use smash::lua2cpp::L2CFighterBase;

    extern "C" {
        // From libsmashline_plugin: the function the game itself had in that slot before any
        // smashline script was installed, or None if it had none.
        fn smashline_get_original_status(fighter: &mut L2CFighterBase, line: StatusLine, status: i32) -> Option<std::ptr::NonNull<()>>;
    }

    /// For a slot vanilla leaves empty (HDR added it): do nothing, like an empty status line.
    unsafe extern "C" fn empty_status(_agent: &mut L2CFighterBase) -> L2CValue {
        L2CValue::I32(0)
    }

    unsafe fn force_vanilla(agent: &mut L2CFighterBase, slots: &[(StatusLine, i32)]) {
        for &(line, kind) in slots {
            let want = match smashline_get_original_status(agent, line, kind) {
                Some(p) => p.as_ptr() as *mut CVoid,
                None => empty_status as *const () as *mut CVoid,
            };
            let have = agent.sv_get_status_func(&L2CValue::I32(kind), &L2CValue::I32(line as i32)).get_ptr();
            if have as *mut CVoid != want {
                agent.sv_set_status_func(L2CValue::I32(kind), L2CValue::I32(line as i32), &mut *want);
            }
        }
    }

    type CVoid = skyline::libc::c_void;

    unsafe fn krool_slots() -> [(StatusLine, i32); 13] {
        use StatusLine::*;
        [
            (Main, *FIGHTER_STATUS_KIND_ATTACK_LW4),
            (MapCorrection, *FIGHTER_STATUS_KIND_ATTACK_LW4),
            (Pre, *FIGHTER_KROOL_STATUS_KIND_SPECIAL_HI_START),
            (Main, *FIGHTER_KROOL_STATUS_KIND_SPECIAL_HI_START),
            (Exit, *FIGHTER_KROOL_STATUS_KIND_SPECIAL_HI_START),
            (Main, *FIGHTER_KROOL_STATUS_KIND_SPECIAL_HI),
            (Main, *FIGHTER_KROOL_STATUS_KIND_SPECIAL_HI_AIR_END),
            (Main, *FIGHTER_KROOL_STATUS_KIND_SPECIAL_HI_FALL),
            (Pre, *FIGHTER_KROOL_STATUS_KIND_SPECIAL_HI_LANDING),
            (Main, *FIGHTER_KROOL_STATUS_KIND_SPECIAL_HI_LANDING),
            // HDR's Pre redirects down special into its own "gut" status; vanilla's never does.
            (Pre, *FIGHTER_STATUS_KIND_SPECIAL_LW),
            (Main, *FIGHTER_STATUS_KIND_SPECIAL_N),
            (Main, *FIGHTER_KROOL_STATUS_KIND_SPECIAL_S_CATCH),
        ]
    }

    unsafe extern "C" fn krool_fix(fighter: &mut L2CFighterCommon) {
        let base = &mut *(fighter as *mut L2CFighterCommon as *mut L2CFighterBase);
        force_vanilla(base, &krool_slots());
    }

    unsafe extern "C" fn ironball_fix(weapon: &mut L2CWeaponCommon) {
        let base = &mut *(weapon as *mut L2CWeaponCommon as *mut L2CFighterBase);
        force_vanilla(base, &[(StatusLine::End, *WEAPON_KROOL_IRONBALL_STATUS_KIND_END)]);
    }

    pub fn install() {
        Agent::new("krool")
            .on_start(krool_fix)
            .on_line(Main, krool_fix)
            .install();
        Agent::new("krool_ironball")
            .on_start(ironball_fix)
            .on_line(Main, ironball_fix)
            .install();
    }
}

// ---- Kirby random copy ability ----------------------------------------------------------------

mod kirby_copy {
    use super::*;

    const MAX_ENTRIES: usize = 8;
    /// A fighter counts as "in the match" if its per-frame callback ran this recently.
    const FRESH_TICKS: u64 = 19_200_000; // 1 s (system tick is 19.2 MHz)

    #[derive(Clone, Copy)]
    struct Entry {
        kind: i32,
        last_seen: u64,
        prev_status: i32,
        /// Kirby only: just finished an entry/respawn and still needs his copy ability.
        pending: bool,
    }

    static mut ENTRIES: [Entry; MAX_ENTRIES] = [Entry { kind: -1, last_seen: 0, prev_status: -1, pending: false }; MAX_ENTRIES];
    static mut RNG: u64 = 0;

    fn now() -> u64 {
        unsafe { skyline::nn::os::GetSystemTick() }
    }

    unsafe fn random(n: usize) -> usize {
        if RNG == 0 {
            RNG = now() | 1;
        }
        RNG ^= RNG >> 12;
        RNG ^= RNG << 25;
        RNG ^= RNG >> 27;
        ((RNG.wrapping_mul(0x2545F4914F6CDD1D) >> 33) % n as u64) as usize
    }

    /// Picks another fighter in the match to copy: (entry id, fighter kind).
    unsafe fn pick_copy_target(own_entry: usize) -> Option<(usize, i32)> {
        let t = now();
        let entries = &*std::ptr::addr_of!(ENTRIES);
        let mut candidates = [(0usize, 0i32); MAX_ENTRIES];
        let mut n = 0;
        for (i, e) in entries.iter().enumerate() {
            if i != own_entry && e.kind >= 0 && e.kind != *FIGHTER_KIND_KIRBY && t.wrapping_sub(e.last_seen) < FRESH_TICKS {
                candidates[n] = (i, e.kind);
                n += 1;
            }
        }
        if n == 0 { None } else { Some(candidates[random(n)]) }
    }

    unsafe extern "C" fn frame(fighter: &mut L2CFighterCommon) {
        let boma: *mut BattleObjectModuleAccessor = fighter.module_accessor;
        let entry_id = WorkModule::get_int(boma, *FIGHTER_INSTANCE_WORK_ID_INT_ENTRY_ID) as usize;
        if entry_id >= MAX_ENTRIES {
            return;
        }
        let kind = app::utility::get_kind(&mut *boma);
        let status = StatusModule::status_kind(boma);
        let e = &mut (*std::ptr::addr_of_mut!(ENTRIES))[entry_id];
        e.kind = kind;
        e.last_seen = now();

        if kind == *FIGHTER_KIND_KIRBY {
            let spawning = |s: i32| s == *FIGHTER_STATUS_KIND_ENTRY || s == *FIGHTER_STATUS_KIND_REBIRTH;
            // Give the copy right after the entry/respawn ends, once Kirby can act.
            if spawning(e.prev_status) && !spawning(status) {
                e.pending = true;
            }
            if status == *FIGHTER_STATUS_KIND_DEAD {
                e.pending = false;
            }
            if e.pending {
                e.pending = false;
                if let Some((target_entry, target_kind)) = pick_copy_target(entry_id) {
                    app::FighterSpecializer_Kirby::copy_setup(
                        boma as *mut app::FighterModuleAccessor,
                        target_entry as i32,
                        app::FighterKind(target_kind),
                        true,
                        false,
                    );
                }
            }
        }
        e.prev_status = status;
    }

    pub fn install() {
        Agent::new("fighter").on_line(Main, frame).install();
    }
}

// ---- auto tech (taunt toggle) -----------------------------------------------------------------

mod auto_tech {
    //! Hold shield + press any taunt (any time), or press a taunt during the intro, to toggle
    //! auto-tech for that player slot. "On" plays
    //! HDR's character-select ding plus a sparkle; "off" plays a thud. The setting stays on that
    //! slot across matches until the game restarts, and the ding replays at each intro while on.
    //!
    //! With auto-tech on, a missed tech is turned into the tech it would have been: landing from
    //! tumble -> tech in place (or tech roll if the stick is held left/right), and bouncing off a
    //! wall / ceiling / floor -> wall tech / ceiling tech / tech in place. The switch happens on the
    //! first frame of the bounce, so it's one frame later than a perfect manual tech.
    use super::*;

    const MAX_ENTRIES: usize = 8;
    const SOUND_ON: &str = "se_system_amiibo_write_2";
    const SOUND_OFF: &str = "se_common_down_m_01";

    static mut ENABLED: [bool; MAX_ENTRIES] = [false; MAX_ENTRIES];
    static mut PREV_STATUS: [i32; MAX_ENTRIES] = [-1; MAX_ENTRIES];

    unsafe fn confirm(boma: *mut BattleObjectModuleAccessor, on: bool) {
        let se = if on { SOUND_ON } else { SOUND_OFF };
        SoundModule::play_se(boma, Hash40::new(se), true, false, false, false, app::enSEType(0));
        if on {
            let zero = smash::phx::Vector3f { x: 0.0, y: 0.0, z: 0.0 };
            EffectModule::req_follow(boma, Hash40::new("sys_level_up"), Hash40::new("top"), &zero, &zero, 1.0, true, 0, 0, 0, 0, 0, false, false);
        }
    }

    unsafe fn taunt_pressed(boma: *mut BattleObjectModuleAccessor) -> bool {
        [*CONTROL_PAD_BUTTON_APPEAL_HI, *CONTROL_PAD_BUTTON_APPEAL_LW, *CONTROL_PAD_BUTTON_APPEAL_S_L, *CONTROL_PAD_BUTTON_APPEAL_S_R]
            .iter()
            .any(|&b| ControlModule::check_button_trigger(boma, b))
    }

    /// Statuses a missed floor tech comes from (tumble / launched).
    unsafe fn is_launched(status: i32) -> bool {
        [
            *FIGHTER_STATUS_KIND_DAMAGE_FLY,
            *FIGHTER_STATUS_KIND_DAMAGE_FLY_ROLL,
            *FIGHTER_STATUS_KIND_DAMAGE_FLY_METEOR,
            *FIGHTER_STATUS_KIND_DAMAGE_FALL,
        ]
        .contains(&status)
    }

    unsafe extern "C" fn frame(fighter: &mut L2CFighterCommon) {
        let boma: *mut BattleObjectModuleAccessor = fighter.module_accessor;
        let entry = WorkModule::get_int(boma, *FIGHTER_INSTANCE_WORK_ID_INT_ENTRY_ID) as usize;
        if entry >= MAX_ENTRIES {
            return;
        }
        let status = StatusModule::status_kind(boma);
        let prev = PREV_STATUS[entry];
        PREV_STATUS[entry] = status;

        if status == *FIGHTER_STATUS_KIND_ENTRY && prev != status && ENABLED[entry] {
            confirm(boma, true); // reminder: still on from an earlier match
        }
        // Toggle: any taunt during the intro, or hold shield + any taunt at any time (taunting
        // out of shield does nothing in vanilla, so this can't trigger by accident). Inputs may
        // be locked during the intro, which is why the shield version exists.
        let shielding = ControlModule::check_button_on(boma, *CONTROL_PAD_BUTTON_GUARD);
        if (status == *FIGHTER_STATUS_KIND_ENTRY || shielding) && taunt_pressed(boma) {
            ENABLED[entry] = !ENABLED[entry];
            confirm(boma, ENABLED[entry]);
            log(&format!("P{} auto-tech {}", entry + 1, if ENABLED[entry] { "ON" } else { "OFF" }));
        }
        if !ENABLED[entry] || prev == status {
            return;
        }

        let tech = if status == *FIGHTER_STATUS_KIND_DOWN && is_launched(prev) {
            let stick_x = ControlModule::get_stick_x(boma);
            Some(if stick_x.abs() > 0.5 { *FIGHTER_STATUS_KIND_PASSIVE_FB } else { *FIGHTER_STATUS_KIND_PASSIVE })
        } else if status == *FIGHTER_STATUS_KIND_DAMAGE_FLY_REFLECT_D {
            Some(*FIGHTER_STATUS_KIND_PASSIVE)
        } else if status == *FIGHTER_STATUS_KIND_DAMAGE_FLY_REFLECT_LR {
            Some(*FIGHTER_STATUS_KIND_PASSIVE_WALL)
        } else if status == *FIGHTER_STATUS_KIND_DAMAGE_FLY_REFLECT_U {
            Some(*FIGHTER_STATUS_KIND_PASSIVE_CEIL)
        } else {
            None
        };
        if let Some(kind) = tech {
            // Immediate change (same call HDR uses); a status *request* can be ignored here.
            fighter.change_status(L2CValue::I32(kind), L2CValue::Bool(false));
            PREV_STATUS[entry] = kind;
            log(&format!("P{} auto-tech: {:#x} -> tech status {:#x}", entry + 1, status, kind));
        }
    }

    pub fn install() {
        Agent::new("fighter").on_line(Main, frame).install();
    }
}

// ---- Kirby down air: fast Melee-Falco-style spike ------------------------------------------------

mod kirby_dair {
    //! Kirby's down air (overrides HDR's at Priority::High):
    //! - startup: animation frames 1-17 play in 5 frames (HDR: 12), so it hits on frame 6;
    //! - instead of HDR's drill (2% every 3 frames), every active frame is one spike hit, like
    //!   Falco's down air in Melee: 12% for the first 4 frames, 9% after, 285 degrees (down,
    //!   slightly forward). Each opponent can only be hit once.
    //! The drill effect and sound scripts are unchanged; only the hitboxes and timing are new.
    use super::*;
    use smash::app::sv_animcmd::frame;
    use smash::phx::Hash40;
    use smash_script::macros::*;

    /// Animation frames 1-17 (the windup) take this many game frames.
    const STARTUP_FRAMES: f32 = 5.0;
    const ANGLE: u64 = 285;

    unsafe fn spike(agent: &mut L2CAgentBase, damage: f32, kbg: i32, bkb: i32, hitlag: f32) {
        // same shape and place as HDR's drill hitbox, a little bigger
        ATTACK(agent, 0, 0, Hash40::new("top"), damage, ANGLE, kbg, 0, bkb, 5.5, 0.0, -1.4, 2.4, Some(0.0), Some(2.3), Some(0.5),
            hitlag, 1.0, *ATTACK_SETOFF_KIND_ON, *ATTACK_LR_CHECK_POS, false, 0, 0.0, 0, false, false, false, false, true,
            *COLLISION_SITUATION_MASK_GA, *COLLISION_CATEGORY_MASK_ALL, *COLLISION_PART_MASK_ALL, false,
            Hash40::new("collision_attr_normal"), *ATTACK_SOUND_LEVEL_L, *COLLISION_SOUND_ATTR_KICK, *ATTACK_REGION_KICK);
    }

    unsafe extern "C" fn game_attackairlw(agent: &mut L2CAgentBase) {
        let lua_state = agent.lua_state_agent;
        let boma = agent.module_accessor;
        frame(lua_state, 1.0);
        FT_MOTION_RATE_RANGE(agent, 1.0, 17.0, STARTUP_FRAMES);
        frame(lua_state, 17.0);
        FT_MOTION_RATE(agent, 1.0);
        if is_excute(agent) {
            WorkModule::on_flag(boma, *FIGHTER_STATUS_ATTACK_AIR_FLAG_ENABLE_LANDING);
        }
        frame(lua_state, 18.0);
        if is_excute(agent) {
            spike(agent, 12.0, 92, 20, 1.2); // clean
        }
        frame(lua_state, 22.0);
        if is_excute(agent) {
            spike(agent, 9.0, 85, 15, 1.0); // late
        }
        frame(lua_state, 35.0);
        if is_excute(agent) {
            AttackModule::clear_all(boma);
        }
        frame(lua_state, 46.0);
        if is_excute(agent) {
            WorkModule::off_flag(boma, *FIGHTER_STATUS_ATTACK_AIR_FLAG_ENABLE_LANDING);
        }
    }

    pub fn install() {
        Agent::new("kirby").acmd("game_attackairlw", game_attackairlw, Priority::High).install();
    }
}

// ---- Joker: more Arsene, "1 MORE!" smash attacks -------------------------------------------------

mod joker {
    //! Joker fun pack, layered on HDR's Joker (his moves themselves are HDR's):
    //! - Arsene no longer adds landing lag to Joker's aerials (HDR adds a few frames per aerial
    //!   while Arsene is out). The landing scripts are overridden at Priority::High.
    //! - The Rebellion Gauge fills faster: +HIT_BONUS on every move that hits (on top of HDR's
    //!   damage-dealt meter) and a slow passive fill, while Arsene isn't out.
    //! - Arsene stays longer: DRAIN_REFUND of his slow drain is given back each frame (damage
    //!   taken still drains it at the normal rate).
    //! - "1 MORE!": a smash attack that hits (not shield) can be cancelled into anything once its
    //!   hitlag ends, with a flash and a sound, like Persona's One More.
    //! - Arsene arriving shakes the screen.
    use super::*;
    use smash::app::sv_animcmd::frame;
    use smash::phx::{Hash40, Vector3f};
    use smash_script::macros::*;

    const MAX_ENTRIES: usize = 8;
    /// Gauge added when a move hits (HDR already adds the damage dealt).
    const HIT_BONUS: f32 = 4.0;
    /// Gauge added every frame while Arsene isn't out (0.02 = full from empty in ~80 s).
    const PASSIVE_PER_FRAME: f32 = 0.02;
    /// Share of Arsene's slow drain given back (0.5 = he lasts about twice as long).
    const DRAIN_REFUND: f32 = 0.5;
    /// Drops bigger than this in one frame are damage, not the slow drain, and aren't refunded.
    const DRAIN_MAX_PER_FRAME: f32 = 1.0;

    static mut PREV_HIT: [bool; MAX_ENTRIES] = [false; MAX_ENTRIES];
    static mut PREV_DOYLE: [bool; MAX_ENTRIES] = [false; MAX_ENTRIES];
    static mut PREV_GAUGE: [f32; MAX_ENTRIES] = [0.0; MAX_ENTRIES];
    static mut ONE_MORE: [bool; MAX_ENTRIES] = [false; MAX_ENTRIES];
    static mut PREV_STATUS: [i32; MAX_ENTRIES] = [-1; MAX_ENTRIES];

    unsafe fn add_gauge(boma: *mut BattleObjectModuleAccessor, entry: i32, amount: f32) {
        app::FighterSpecializer_Jack::add_rebel_gauge(boma, app::FighterEntryID(entry), amount);
    }

    unsafe fn is_smash_attack(status: i32) -> bool {
        [*FIGHTER_STATUS_KIND_ATTACK_S4, *FIGHTER_STATUS_KIND_ATTACK_HI4, *FIGHTER_STATUS_KIND_ATTACK_LW4].contains(&status)
    }

    unsafe extern "C" fn frame_main(fighter: &mut L2CFighterCommon) {
        let boma: *mut BattleObjectModuleAccessor = fighter.module_accessor;
        if app::utility::get_kind(&mut *boma) != *FIGHTER_KIND_JACK {
            return;
        }
        let entry_id = WorkModule::get_int(boma, *FIGHTER_INSTANCE_WORK_ID_INT_ENTRY_ID);
        let entry = entry_id as usize;
        if entry >= MAX_ENTRIES {
            return;
        }
        let status = StatusModule::status_kind(boma);
        if status != PREV_STATUS[entry] {
            PREV_STATUS[entry] = status;
            ONE_MORE[entry] = false;
        }
        let doyle = WorkModule::is_flag(boma, *FIGHTER_JACK_INSTANCE_WORK_ID_FLAG_DOYLE);
        let hit = AttackModule::is_infliction_status(boma, *COLLISION_KIND_MASK_HIT);
        let new_hit = hit && !PREV_HIT[entry];
        PREV_HIT[entry] = hit;
        let zero = Vector3f { x: 0.0, y: 0.0, z: 0.0 };

        // Arsene arrives
        if doyle && !PREV_DOYLE[entry] {
            CameraModule::req_quake(boma, *CAMERA_QUAKE_KIND_M);
        }
        PREV_DOYLE[entry] = doyle;

        // gauge
        if status != *FIGHTER_STATUS_KIND_ENTRY {
            if doyle {
                let g = WorkModule::get_float(boma, *FIGHTER_JACK_INSTANCE_WORK_ID_FLOAT_REBEL_GAUGE);
                let drop = PREV_GAUGE[entry] - g;
                if drop > 0.0 && drop < DRAIN_MAX_PER_FRAME && g > 0.0 {
                    let refunded = g + drop * DRAIN_REFUND;
                    WorkModule::set_float(boma, refunded, *FIGHTER_JACK_INSTANCE_WORK_ID_FLOAT_REBEL_GAUGE);
                    PREV_GAUGE[entry] = refunded;
                } else {
                    PREV_GAUGE[entry] = g;
                }
            } else {
                if new_hit {
                    add_gauge(boma, entry_id, HIT_BONUS);
                }
                add_gauge(boma, entry_id, PASSIVE_PER_FRAME);
                PREV_GAUGE[entry] = WorkModule::get_float(boma, *FIGHTER_JACK_INSTANCE_WORK_ID_FLOAT_REBEL_GAUGE);
            }
        }

        // 1 MORE!
        if is_smash_attack(status) && hit && !StopModule::is_stop(boma) {
            if !ONE_MORE[entry] {
                ONE_MORE[entry] = true;
                let pos = Vector3f { x: 0.0, y: 12.0, z: 0.0 };
                EffectModule::req_follow(boma, Hash40::new("sys_smash_flash"), Hash40::new("top"), &pos, &zero, 1.6, true, 0, 0, 0, 0, 0, false, false);
                SoundModule::play_se(boma, Hash40::new("se_common_criticalhit"), true, false, false, false, app::enSEType(0));
            }
            CancelModule::enable_cancel(boma);
        }
    }

    // HDR: FT_MOTION_RATE(landing + param_doyle.landing_attack_air_*_add) while Arsene is out.
    // Ours: the normal landing lag either way.
    unsafe extern "C" fn game_landingairn(agent: &mut L2CAgentBase) {
        let lua_state = agent.lua_state_agent;
        frame(lua_state, 3.0);
        if is_excute(agent) {
            STOP_SE(agent, Hash40::new("se_jack_attackair_n01"));
        }
    }

    unsafe extern "C" fn game_landingair_plain(_agent: &mut L2CAgentBase) {}

    pub fn install() {
        Agent::new("jack")
            .acmd("game_landingairn", game_landingairn, Priority::High)
            .acmd("game_landingairf", game_landingair_plain, Priority::High)
            .acmd("game_landingairb", game_landingair_plain, Priority::High)
            .acmd("game_landingairhi", game_landingair_plain, Priority::High)
            .acmd("game_landingairlw", game_landingair_plain, Priority::High)
            .install();
        Agent::new("fighter").on_line(Main, frame_main).install();
    }
}

// ---- final hit, bigger ---------------------------------------------------------------------------

mod final_hit {
    //! HDR's final-hit moment (the game-ending KO), made bigger:
    //! 1. the camera snaps to a close-up of the KO'd fighter, in slow motion, while HDR's lightning
    //!    background flips between its red and blue versions;
    //! 2. the camera slowly zooms back out;
    //! 3. then it snaps out fast with a big screen shake and a second "KUNG", and the slow motion
    //!    cuts off, so the fighter rockets away at full speed.
    //! The KUNG itself (the bumper sound, slowed to 0.7x) is a file, not code: it replaces
    //! `se_common_boss_down` in parry-sound's se_common.patch3audio.
    //!
    //! Everything is tunable without rebuilding in sd:/tuff_final_hit.txt (written with the
    //! defaults the first time it's missing, read again at every final hit).
    //!
    //! HDR plays `se_common_boss_down` on the KO'd fighter at the exact moment of the final hit,
    //! so this watches for that sound starting. Timing uses the system clock, not frames, because
    //! everything runs in slow motion.
    //!
    //! Camera notes from testing: the game has no way to rotate the camera (CameraModule only
    //! zooms / shakes / changes range), and the final-smash camera (CAM_ZOOM_IN_FINAL) can only be
    //! aimed once, so a 360 orbit isn't possible. This uses the normal zoom (the smash-attack
    //! charge zoom): CameraModule::zoom_in(frames, 0, magnification, offset, false) and
    //! zoom_out(frames).
    use super::*;
    use smash::app::sv_animcmd;
    use smash::phx::{Hash40, Vector2f};
    use smash_script::lua_args;

    const CONFIG_PATH: &str = "sd:/tuff_final_hit.txt";
    const SLOW_MUL: u8 = 8; // same slow motion as HDR
    /// The two backgrounds the strobe flips between (HDR's team-color versions of the final-hit
    /// background), and every version that might be showing.
    const STROBE: [&str; 2] = ["sys_bg_finishhit_r", "sys_bg_finishhit_b"];
    const ALL_BACKGROUNDS: [&str; 9] = [
        "sys_bg_finishhit", "sys_bg_finishhit_r", "sys_bg_finishhit_b", "sys_bg_finishhit_y", "sys_bg_finishhit_g",
        "sys_bg_finishhit_o", "sys_bg_finishhit_c", "sys_bg_finishhit_m", "sys_bg_finishhit_p",
    ];
    const TICKS_PER_SECOND: f32 = 19_200_000.0;
    const MAX_ENTRIES: usize = 8;

    #[derive(Clone, Copy)]
    struct Config {
        seconds: f32,
        zoom: bool,
        zoom_start: f32,
        zoom_end: f32,
        zoom_in_frames: f32,
        zoom_step_seconds: f32,
        fast_out_frames: f32,
        shake: bool,
        kung_again: bool,
        flash: bool,
        flash_seconds: f32,
        dark_seconds: f32,
    }

    const DEFAULTS: Config = Config {
        seconds: 2.4,
        zoom: true,
        zoom_start: 3.0,
        zoom_end: 2.0,
        zoom_in_frames: 3.0,
        zoom_step_seconds: 0.1,
        fast_out_frames: 5.0,
        shake: true,
        kung_again: true,
        flash: true,
        flash_seconds: 0.25,
        dark_seconds: 99.0,
    };

    const CONFIG_TEXT: &str = "\
# Project TUFF - final hit settings. Read at every final hit, no rebuild needed.
# Lines are  name = value  ; anything after # is ignored.
#
# What happens: the camera snaps to a close-up of the KO'd fighter in slow motion, slowly zooms
# back out, then snaps out fast with a screen shake while the slow motion cuts off, so they go
# flying at full speed.

seconds = 2.4            # how long the slow-motion part lasts before the fast snap out
zoom = 1                 # 1 = close-up + zoom out, 0 = leave the camera alone
zoom_start = 3.0         # close-up zoom at the hit (1 = normal, bigger = closer)
zoom_end = 2.0           # zoom it slowly eases out to by the end of the slow part
zoom_in_frames = 3       # frames to snap into the close-up
zoom_step_seconds = 0.1  # how often the slow zoom-out gets a new zoom level
fast_out_frames = 5      # frames for the fast snap back out (smaller = faster)
shake = 1                # 1 = big screen shake at the snap
kung_again = 1           # 1 = play the KUNG again at the snap
flash = 1                # 1 = background flips red / blue, 0 = HDR's normal team color
flash_seconds = 0.25     # how long each red / blue lasts
dark_seconds = 99        # HDR blacks out the stage at the final hit; switch that off after this
                         # many seconds (99 = keep it until the snap, like HDR)
";

    fn parse_bool(v: &str) -> bool {
        matches!(v, "1" | "true" | "on" | "yes")
    }

    fn load_config() -> Config {
        let text = match std::fs::read_to_string(CONFIG_PATH) {
            Ok(t) => t,
            Err(_) => {
                let _ = std::fs::write(CONFIG_PATH, CONFIG_TEXT);
                return DEFAULTS;
            }
        };
        let mut c = DEFAULTS;
        for line in text.lines() {
            let line = line.split('#').next().unwrap_or("");
            let Some((k, v)) = line.split_once('=') else { continue };
            let (k, v) = (k.trim(), v.trim());
            let f = v.parse::<f32>().ok();
            match (k, f) {
                ("seconds", Some(x)) => c.seconds = x.clamp(0.2, 20.0),
                ("zoom_start", Some(x)) => c.zoom_start = x.max(1.0),
                ("zoom_end", Some(x)) => c.zoom_end = x.max(1.0),
                ("zoom_in_frames", Some(x)) => c.zoom_in_frames = x.max(0.0),
                ("zoom_step_seconds", Some(x)) => c.zoom_step_seconds = x.max(0.02),
                ("fast_out_frames", Some(x)) => c.fast_out_frames = x.max(0.0),
                ("flash_seconds", Some(x)) => c.flash_seconds = x.max(0.02),
                ("dark_seconds", Some(x)) => c.dark_seconds = x,
                ("zoom", _) => c.zoom = parse_bool(v),
                ("shake", _) => c.shake = parse_bool(v),
                ("kung_again", _) => c.kung_again = parse_bool(v),
                ("flash", _) => c.flash = parse_bool(v),
                _ => {}
            }
        }
        c
    }

    static mut CONFIG: Config = DEFAULTS;
    static mut START: [u64; MAX_ENTRIES] = [0; MAX_ENTRIES]; // 0 = not running
    static mut WAS_PLAYING: [bool; MAX_ENTRIES] = [false; MAX_ENTRIES];
    static mut SHOWN: [i32; MAX_ENTRIES] = [-1; MAX_ENTRIES]; // which STROBE background is up
    static mut ZOOM_STEP: [i32; MAX_ENTRIES] = [-1; MAX_ENTRIES];
    static mut DARK_OFF: [bool; MAX_ENTRIES] = [false; MAX_ENTRIES];
    /// While the second KUNG plays, don't mistake it for a new final hit.
    static mut IGNORE_SOUND: [bool; MAX_ENTRIES] = [false; MAX_ENTRIES];

    fn now() -> u64 {
        unsafe { skyline::nn::os::GetSystemTick() }
    }

    /// Starts a full-screen background effect (the final-smash / final-hit kind). Arguments as
    /// in Meta Knight's final smash: kind, x, y, z, rot x, y, z, scale.
    unsafe fn background(fighter: &mut L2CFighterCommon, kind: &str) {
        fighter.clear_lua_stack();
        lua_args!(fighter, Hash40::new(kind), 0.0f32, 0.0f32, 0.0f32, 0.0f32, 0.0f32, 0.0f32, 1.0f32);
        sv_animcmd::EFFECT_GLOBAL_BACK_GROUND(fighter.lua_state_agent);
        fighter.clear_lua_stack();
    }

    /// Turns off every effect of one kind, the way HDR ends its own final-hit backgrounds.
    unsafe fn effect_off(fighter: &mut L2CFighterCommon, kind: &str) {
        fighter.clear_lua_stack();
        lua_args!(fighter, Hash40::new(kind), false, false);
        sv_animcmd::EFFECT_OFF_KIND(fighter.lua_state_agent);
        fighter.clear_lua_stack();
    }

    unsafe fn zoom(fighter: &mut L2CFighterCommon, frames: f32, mag: f32) {
        let zero = Vector2f { x: 0.0, y: 0.0 };
        CameraModule::zoom_in(fighter.module_accessor, frames as i32, 0, mag, &zero, false);
    }

    unsafe fn start(entry: usize) {
        CONFIG = load_config();
        let c = CONFIG;
        SHOWN[entry] = -1;
        ZOOM_STEP[entry] = -1;
        DARK_OFF[entry] = false;
        START[entry] = now();
        log(&format!("P{} final hit: start (seconds {} zoom {} {}->{} fast {} shake {} kung {} flash {})",
            entry + 1, c.seconds, c.zoom, c.zoom_start, c.zoom_end, c.fast_out_frames, c.shake, c.kung_again, c.flash));
    }

    /// The snap: fast zoom out, shake, second KUNG, slow motion and backgrounds off.
    unsafe fn finish(fighter: &mut L2CFighterCommon, entry: usize, why: &str) {
        let boma = fighter.module_accessor;
        let c = CONFIG;
        if c.flash {
            for k in ALL_BACKGROUNDS {
                effect_off(fighter, k);
            }
            effect_off(fighter, "sys_bg_black");
        }
        if c.zoom {
            CameraModule::zoom_out(boma, c.fast_out_frames as i32);
        }
        SlowModule::clear_whole(boma);
        if why == "time" {
            if c.shake {
                CameraModule::req_quake(boma, *CAMERA_QUAKE_KIND_XL);
            }
            if c.kung_again {
                IGNORE_SOUND[entry] = true;
                SoundModule::play_se(boma, Hash40::new("se_common_boss_down"), false, false, false, false, app::enSEType(0));
            }
        }
        START[entry] = 0;
        log(&format!("P{} final hit: end ({})", entry + 1, why));
    }

    unsafe extern "C" fn frame(fighter: &mut L2CFighterCommon) {
        let boma: *mut BattleObjectModuleAccessor = fighter.module_accessor;
        let entry = WorkModule::get_int(boma, *FIGHTER_INSTANCE_WORK_ID_INT_ENTRY_ID) as usize;
        if entry >= MAX_ENTRIES {
            return;
        }
        let playing = SoundModule::is_playing(boma, Hash40::new("se_common_boss_down"));
        if !playing {
            IGNORE_SOUND[entry] = false;
        }
        if playing && !WAS_PLAYING[entry] && START[entry] == 0 && !IGNORE_SOUND[entry] {
            start(entry);
        }
        WAS_PLAYING[entry] = playing;
        if START[entry] == 0 {
            return;
        }

        let c = CONFIG;
        let t = now().wrapping_sub(START[entry]) as f32 / TICKS_PER_SECOND;
        let status = StatusModule::status_kind(boma);
        if t >= c.seconds {
            return finish(fighter, entry, "time");
        }
        if status == *FIGHTER_STATUS_KIND_DEAD || status == *FIGHTER_STATUS_KIND_REBIRTH || status == *FIGHTER_STATUS_KIND_STANDBY {
            return finish(fighter, entry, "KO'd");
        }
        if !DARK_OFF[entry] && t >= c.dark_seconds {
            DARK_OFF[entry] = true;
            effect_off(fighter, "sys_bg_black");
        }
        // HDR switches the slow motion off after ~25 frames; keep it going.
        if SlowModule::whole_mag(boma) <= 1 {
            SlowModule::set_whole(boma, SLOW_MUL, 30);
        }
        if c.flash {
            let pick = (t / c.flash_seconds) as i32 % 2;
            if pick != SHOWN[entry] {
                SHOWN[entry] = pick;
                for k in ALL_BACKGROUNDS {
                    effect_off(fighter, k);
                }
                background(fighter, STROBE[pick as usize]);
            }
        }
        if c.zoom {
            // step 0 snaps into the close-up; later steps ease the zoom out a little at a time,
            // each one gliding over the length of a step (at 60 fps)
            let step = (t / c.zoom_step_seconds) as i32;
            if step != ZOOM_STEP[entry] {
                ZOOM_STEP[entry] = step;
                if step == 0 {
                    zoom(fighter, c.zoom_in_frames, c.zoom_start);
                } else {
                    let k = ((step + 1) as f32 * c.zoom_step_seconds / c.seconds).min(1.0);
                    let eased = k * k; // starts slow, picks up toward the snap
                    zoom(fighter, c.zoom_step_seconds * 60.0, c.zoom_start + (c.zoom_end - c.zoom_start) * eased);
                }
            }
        }
    }

    pub fn install() {
        Agent::new("fighter").on_line(Main, frame).install();
    }
}

