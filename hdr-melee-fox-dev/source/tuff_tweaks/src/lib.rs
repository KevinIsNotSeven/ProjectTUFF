//! Project TUFF character tweaks layered on HDR.
//!
//! - **K. Rool back to his base Ultimate moveset.** Every move script and status script HDR
//!   overrides on K. Rool and his articles (backpack, crown, ironball) is overridden again at
//!   `Priority::High` with a compiled copy of the vanilla script (see vanilla_acmd.rs); status
//!   scripts get the game's original function written back into the status table (see krool_status). The lists
//!   come straight from HDR v0.50.0's `fighters/krool/src`. HDR's animation/param files for him
//!   are moved out of the mods separately. Not revertable from here: HDR's belly-armor hook
//!   (a code hook inside HDR's plugin), his special fast-fall, and the crown's reflect rule.
//! - **Dedede's down tilt back to base Ultimate** (same method, `attacklw3` scripts).
//! - **Kirby gets a random copy ability** when he first becomes actionable at the start of a
//!   match and after every respawn. It's picked from the other fighters in the match: their files
//!   are loaded, so it's the same situation as a normal swallow (copying an absent fighter could
//!   reference files that aren't loaded).
//! - **Kirby down air**: frame-6 Melee-Falco-style spike instead of HDR's drill (see kirby_dair).
//! - **Joker**: no Arsene landing-lag penalty, faster/longer Arsene, "1 MORE!" smash-attack
//!   cancels (see joker).
//! - **Auto-tech toggle** per player (see auto_tech).
//! - **Bigger final hit**: slow-mo close-up, red/blue strobe, slow then fast zoom out (see final_hit; tunable in
//!   sd:/tuff_final_hit.txt).

use smash::app::{self, lua_bind::*, BattleObjectModuleAccessor};
use smash::lib::lua_const::*;
use smash::lua2cpp::{L2CFighterCommon, L2CWeaponCommon};
use smash::lib::L2CValue;
use smashline::*;

/// Temporary debug log: sd:/tuff_tweaks_log.txt (capped at 300 lines).
static mut LOG_LINES: u32 = 0;
fn log(msg: &str) {
    unsafe {
        if LOG_LINES >= 300 {
            return;
        }
        LOG_LINES += 1;
    }
    use std::io::Write;
    if let Ok(mut f) = std::fs::OpenOptions::new().create(true).append(true).open("sd:/tuff_tweaks_log.txt") {
        let _ = writeln!(f, "{}", msg);
    }
}

// ---- vanilla move scripts -----------------------------------------------------------------------
